"""Phoenix and LangSmith are retired (#322, ADR 0023): no runtime, eval, infra, deploy, or doc file names either tool.

Only history may: ADRs, plans, reviews, a dated design spec, the PRD's "Changes from" rows, and the generated OpenWiki
pages. The few remaining code files are the safety net that keeps langchain-core's own cloud tracing off (langchain-core
still ships that client, and a developer's shell can switch it on), and the tests of that net."""

import re
import shutil
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
RETIRED = re.compile(r"phoenix|langsmith", re.IGNORECASE)

HISTORY_PREFIXES = (
    "sdd/adr/",
    "sdd/plans/",
    "sdd/reviews/",
    "sdd/specs/2026-10-14-off-hours-and-langfuse-host-design.md",
    "openwiki/",  # generated by the scheduled OpenWiki workflow
    ".agents/",  # third-party skills
    ".claude/",
)
KILL_SWITCH = {
    "backend/src/smart_tutor/shared/adapters/tracing.py",  # sets the LANGSMITH_* switches to "false" at startup
    "backend/pyproject.toml",  # the import contract that keeps runtime code off the langsmith client
    "backend/tests/conftest.py",
    "backend/tests/fakes/tracing.py",
    "backend/tests/test_tests_never_trace.py",
    "backend/tests/unit/evals/test_dataset.py",  # no eval module imports it
}
LOCK_FILES = {"backend/uv.lock", "infra/uv.lock", "platform/langfuse/uv.lock"}  # langchain-core depends on langsmith
THIS_FILE = "backend/tests/test_retired_tracing_tools.py"
PRD = "sdd/prd.md"


def tracked_files() -> list[str]:
    if shutil.which("git") is None or not (REPO / ".git").exists():
        pytest.skip("needs a git checkout")
    out = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        cwd=REPO,
        check=True,
        capture_output=True,
    ).stdout
    return [name for name in out.decode().split("\0") if name]


def is_exempt(name: str) -> bool:
    return name.startswith(HISTORY_PREFIXES) or name in KILL_SWITCH | LOCK_FILES | {THIS_FILE}


def mentions(name: str) -> list[int]:
    try:
        lines = (REPO / name).read_text(encoding="utf-8").splitlines()
    except (UnicodeDecodeError, FileNotFoundError):  # binary files, and files deleted in the working tree
        return []
    history = name == PRD
    return [
        number
        for number, line in enumerate(lines, start=1)
        if RETIRED.search(line) and not (history and line.startswith("| **Changes from"))
    ]


def test_no_live_file_names_phoenix_or_langsmith() -> None:
    offenders = {name: lines for name in tracked_files() if not is_exempt(name) and (lines := mentions(name))}
    assert offenders == {}, "Phoenix and LangSmith are retired; remove these (or move the text into history)"


def test_the_exemptions_still_exist_and_still_need_it() -> None:
    files = set(tracked_files())
    stale = sorted(name for name in KILL_SWITCH if name not in files or not mentions(name))
    assert stale == [], "drop these from KILL_SWITCH: they no longer name the retired tools"
