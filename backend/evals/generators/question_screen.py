"""The question-screen dataset (#199, PRD D28): benign study questions and the injection taxonomy's attack seeds.

Usage: uv run python -m evals.generators.question_screen build

`build` writes datasets/question_screen.yaml from adversarial/benign_questions.yaml (label `benign`, topic = its
group) and the prompt seeds of adversarial/taxonomy.yaml (label `attack`, topic = the category). A unit test fails
when the file is stale. The screen sees only the question, so a seed's learner, document limit, and history are
dropped.
"""

import argparse
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import yaml

from evals.generators.injection import _dump, load_taxonomy, seed_rows

EVALS = Path(__file__).parents[1]
BENIGN = EVALS / "adversarial" / "benign_questions.yaml"
DATASET = EVALS / "datasets" / "question_screen.yaml"
DATASET_NAME = "smart-tutor-question-screen"
HEADER = """\
# GENERATED by `uv run python -m evals.generators.question_screen build` from adversarial/benign_questions.yaml and
# adversarial/taxonomy.yaml: don't edit.
# What the question screen (#199) sees: the learner's question alone.
#
# inputs:  question.
# outputs: label (benign: must pass; attack: should be caught); topic (benign: its group; attack: taxonomy category).
"""


def load_benign(path: Path = BENIGN) -> dict[str, list[str]]:
    topics: dict[str, list[str]] = yaml.safe_load(path.read_text(encoding="utf-8"))["topics"]
    return topics


def rows(benign: Mapping[str, Sequence[str]], taxonomy: Mapping[str, Any]) -> list[dict[str, Any]]:
    found = [
        {"inputs": {"question": question}, "outputs": {"label": "benign", "topic": topic}}
        for topic, questions in benign.items()
        for question in questions
    ]
    found += [
        {
            "inputs": {"question": row["inputs"]["question"]},
            "outputs": {"label": "attack", "topic": row["outputs"]["category"]},
        }
        for row in seed_rows(taxonomy)
    ]
    seen: set[str] = set()
    for row in found:
        question = row["inputs"]["question"]
        if question in seen:
            raise ValueError(f"the question appears twice in the question-screen dataset: {question[:80]!r}")
        seen.add(question)
    return found


def render_dataset(benign: Mapping[str, Sequence[str]], taxonomy: Mapping[str, Any]) -> str:
    body = {
        "name": DATASET_NAME,
        "description": "Benign study questions and prompt attacks for the Bedrock question screen (generated).",
        # full only: a 1% false-positive gate means nothing on a 30-row subset, and CI has no guardrail to call
        "splits": ["full"],
        "examples": rows(benign, taxonomy),
    }
    return HEADER + _dump(body)


def build(benign_path: Path = BENIGN, out: Path = DATASET) -> None:
    out.write_text(render_dataset(load_benign(benign_path), load_taxonomy()), encoding="utf-8", newline="\n")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("build", help="write datasets/question_screen.yaml")
    args = parser.parse_args(argv)
    if args.command == "build":
        build()
        print(f"Wrote {DATASET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
